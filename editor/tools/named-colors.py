#!/usr/bin/env python3
"""Writes web/src/colors.js from color/kotlin/com/xalitoria/color/NamedColor.kt (and the sixteen colors of CodedColor.kt), so that the
editor draws `{#name}` and `{#a>}gradient{#b<}` in the colors the plugin uses. Run it after the table changes:

    python3 -I menu/editor/tools/named-colors.py
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[3] / 'color/kotlin/com/xalitoria/color'
coded = {}
for m in re.finditer(r"^\s+([A-Z_]+)\s*\('(.)',\s*0x([0-9A-Fa-f]{6})", (root / 'CodedColor.kt').read_text(), re.M):
    coded[m.group(1)] = int(m.group(3), 16)
for m in re.finditer(r"^\s+([A-Z_]+)\s*\(([A-Z_]+)\)", (root / 'CodedColor.kt').read_text(), re.M):
    if m.group(2) in coded: coded.setdefault(m.group(1), coded[m.group(2)])
for m in re.finditer(r"\b([A-Z_]+)\(([A-Z_]+)\)", (root / 'CodedColor.kt').read_text()):
    if m.group(2) in coded: coded.setdefault(m.group(1), coded[m.group(2)])
values = {}
order = []
text = (root / 'NamedColor.kt').read_text().split('companion object')[0]
for m in re.finditer(r"\b([A-Z][A-Z0-9_]*)\s*\(\s*(0x[0-9A-Fa-f]+|CodedColor\.[A-Z_]+|[A-Z][A-Z0-9_]*)\s*\)", text):
    name, arg = m.groups()
    if name in ('CodedColor',): continue
    if arg.startswith('0x'): value = int(arg, 16)
    elif arg.startswith('CodedColor.'): value = coded[arg.split('.')[1]]
    else:
        if arg not in values: continue
        value = values[arg]
    if name not in values:
        values[name] = value
        order.append(name)
seen = {}
for name in order:
    key = name.replace('_', '').lower()
    seen.setdefault(key, values[name])
body = ','.join(f'{k}:{v:06x}' for k, v in seen.items())
out = pathlib.Path(__file__).resolve().parents[1] / 'web/src/colors.js'
out.write_text(f"""// GENERATED by tools/named-colors.py from NamedColor.kt of the color module. Do not edit: run the script again.
// The names that `{{#name}}` takes (case and underscores do not matter, the first of equal names counts), each with its color.

const TABLE = '{body}'

/** @type {{Map<string, string>}} name without underscores, in lower case, to `#rrggbb` */
export const NAMED_COLORS = new Map(TABLE.split(',').map((entry) => {{ const [name, hex] = entry.split(':'); return [name, `#${{hex}}`] }}))
""")
print(len(seen), 'names')
